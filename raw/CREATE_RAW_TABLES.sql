--  CREATE DATABASE AND SCHEMA IF NOT EXISTS
CREATE DATABASE DBT_DEMO;
CREATE SCHEMA DBT_DEMO.RAW;

-- SWITCH ROLE, DATABASE AND SCHEMA
USE ROLE ACCOUNTADMIN;
USE DATABASE DBT_DEMO;
USE SCHEMA DBT_DEMO.RAW;

-- CREATE RAW STAGE TABLES
-- Create RAW_CUSTOMERS
CREATE OR REPLACE TABLE DBT_DEMO.RAW.CUSTOMERS (
 CUSTOMER_ID INTEGER,
 CUSTOMER_NAME VARCHAR,
 STATUS VARCHAR,
 CREATED_AT TIMESTAMP
);

