-- Create RAW_PRODUCTS
CREATE OR REPLACE TABLE DBT_DEMO.RAW.PRODUCTS (
 PRODUCT_ID INTEGER,
 PRODUCT_NAME VARCHAR,
 PRICE NUMBER(10,2),
 CREATED_AT TIMESTAMP
);

